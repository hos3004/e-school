<?php

declare(strict_types=1);

namespace Modules\VirtualClassroom\Domain\Contracts;

/**
 * هل فُتحت غرفة هذه الحصة فعلًا؟ — سؤال جماعي بإجابة واحدة لكل حصة.
 *
 * الفارق الذي يقيسه هذا العقد هو أهم فارق في طابور الحصص غير المقفلة: حصة
 * فُتحت غرفتها تعني **عملًا تمّ** ينتظر اعتمادًا، وحصة لم تُفتح غرفتها إطلاقًا
 * تعني سؤالًا للمعلمة عمّا جرى. الرقم المجمّع بلا هذا التقسيم يدفع المدير إلى
 * فعل واحد لحالتين متناقضتين.
 *
 * جماعي عمدًا: البطاقات تعرض عشرات الحصص وتُفتح كل صباح، فنداء لكل حصة يضاعف
 * كلفة الصفحة بلا داعٍ. ولا يقيس هذا العقد صحة الغرفة (`health_status`) لأنها
 * غير مقيسة أصلًا في الإنتاج — يقيس واقعة مسجَّلة: هل بدأت الغرفة.
 */
interface ClassroomStartedFlagQuery
{
    /**
     * @param list<string> $sessionIds
     * @return array<string, bool> معرّف الحصة ← هل فُتحت غرفتها. الحصص بلا غرفة تعود false.
     */
    public function forSessionIds(array $sessionIds): array;
}
