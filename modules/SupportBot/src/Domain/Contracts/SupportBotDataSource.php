<?php

declare(strict_types=1);

namespace Modules\SupportBot\Domain\Contracts;

use Modules\SupportBot\Domain\Enums\BotTopic;

/**
 * الباب **الوحيد** الذي تدخل منه بيانات المنصة إلى سياق البوت.
 *
 * دالة واحدة لا عشر دوال، وهذا القرار متعمّد تمامًا:
 *
 *  1. **أقل ما يلزم لهذا السؤال.** التنفيذ يقرأ حسب الموضوع فقط، فلا تخرج
 *     بيانات لم يسأل عنها أحد. عقد بعشر دوال قراءة كان سيغري المستدعي بجمع
 *     كل شيء «احتياطيًا» ثم إرساله للمزوّد.
 *
 *  2. **موضع واحد للمراجعة.** كل ما يغادر قاعدة البيانات نحو نموذج خارجي يمر
 *     من هنا. مراجعة الخصوصية تقرأ ملفًا واحدًا بدل تتبّع مسارات متفرقة.
 *
 *  3. **الصلاحيات في التنفيذ لا في العقد.** التنفيذ يعيش في app/ لأنه يركّب
 *     قراءات من موديولات عدة، ويلزمه أن يفحص `$user->can()` وسياسة كل مورد
 *     تمامًا كما لو فتح المستخدم الصفحة بيده. ما لا يراه من الموقع لا يصل هنا.
 *
 * التنفيذ ملزم كذلك بألّا يعيد هاتفًا ولا بريدًا ولا رقمًا قوميًا مهما كان
 * السائل، وألّا يعيد أي مبلغ مالي — الأخير مضمون فوق ذلك بسياج في BotTopic.
 */
interface SupportBotDataSource
{
    /**
     * حقائق مختصرة تخص **هذا المستخدم** وتفيد في الإجابة عن **هذا الموضوع**.
     *
     * تُعاد كأزواج (عنوان، قيمة) جاهزة للعرض بلغة المستخدم، لا ككيانات. السبب
     * أن ما يُبنى هنا سيُدرَج نصًّا في رسالة النظام، والنموذج لا يحتاج معرّفات
     * ولا بنية — يحتاج جملًا صحيحة.
     *
     * قائمة فارغة تعني «لا بيانات تخص هذا الموضوع»، وهي نتيجة مشروعة: البوت
     * يجيب عندها من المعرفة العامة وحدها.
     *
     * @return list<array{label: string, value: string}>
     */
    public function factsFor(string $organizationId, string $userId, BotTopic $topic, string $locale): array;
}
