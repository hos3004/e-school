<?php

declare(strict_types=1);

namespace Modules\SupportBot\Domain\Enums;

/**
 * نوع النص المخزَّن في قاعدة معرفة البوت.
 *
 * الثلاثة في جدول واحد لأنها تشترك في كل شيء: قابلة للتحرير من اللوحة، لها
 * لغة، ولها صف عام يغطّيه صف المؤسسة، وتُطفأ بـis_active بدل الحذف. ما يفرقها
 * هو موضعها في مسار الإجابة فقط.
 */
enum EntryKind: string
{
    /**
     * توجيه للنموذج: النبرة، الأسلوب، ما يتجنبه. يدخل ضمن رسالة النظام.
     *
     * لا يُعرض للمستخدم أبدًا، ولا يُعتمد عليه كحارس: التوجيه رجاء، والحارس
     * كود.
     */
    case Instruction = 'instruction';

    /** معلومة عن المنصة أو سياسات المدرسة يستند إليها الرد. */
    case Knowledge = 'knowledge';

    /**
     * ردّ معدّ مسبقًا يُرسَل حرفيًا كما هو دون مرور بالنموذج.
     *
     * هذا ما يصل المستخدم في وضعَي الإرشاد والاعتذار، ولذلك فصياغته هي واجهة
     * الأكاديمية الحقيقية أمام أكثر اللحظات حساسية.
     */
    case Reply = 'reply';

    public function label(): string
    {
        return __('supportbot::entry_kinds.'.$this->value);
    }
}
