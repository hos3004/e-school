<?php

declare(strict_types=1);

namespace Modules\SupportBot\Domain\Enums;

/**
 * قرار الحارس لموضوع معيّن أمام فئة معيّنة.
 *
 * ثلاثة أوضاع لا اثنان، لأن «ممنوع» وحدها كانت ستجعل البوت حائطًا. الوضع
 * الأوسط — الإرشاد — هو ما طلبه صاحب المنصة حرفيًا: لا يقول الرقم، لكنه يقول
 * الطريق، ويقوله بلباقة.
 */
enum TopicMode: string
{
    /** يُجاب عادةً: نداء الرد يحدث، والبيانات تُقرأ بصلاحيات المستخدم نفسه. */
    case Allow = 'allow';

    /**
     * يُرشَد ولا يُجاب: لا نداء ثانٍ للنموذج إطلاقًا، بل يُعاد نص معدّ مسبقًا
     * يشرح الطريق أو الجهة المختصة.
     *
     * انعدام النداء الثاني مقصود وليس توفيرًا: ما دام النموذج لم يُستدعَ، فلا
     * وجود لاحتمال أن يذكر رقمًا.
     */
    case Guide = 'guide';

    /** يُعتذر بلباقة: بيانات شخص آخر مثلًا. أيضًا بلا نداء ثانٍ. */
    case Deny = 'deny';

    /** هل يُسمح بمناداة النموذج لصياغة رد حر؟ */
    public function allowsGeneration(): bool
    {
        return $this === self::Allow;
    }

    public function label(): string
    {
        return __('support_bot::modes.'.$this->value);
    }
}
